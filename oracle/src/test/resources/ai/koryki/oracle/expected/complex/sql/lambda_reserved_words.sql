-- Words that are reserved in SQL are legal names for a lambda parameter.
SELECT
  t.nr
, CASE WHEN t.scores IS NULL THEN NULL ELSE CAST(MULTISET(SELECT LA0.X * 2 FROM (SELECT COLUMN_VALUE X, ROWNUM I FROM TABLE(t.scores) Z) LA0 ORDER BY LA0.I) AS SYS.ODCINUMBERLIST) END AS doubled
, CASE WHEN t.scores IS NULL THEN NULL ELSE CAST(MULTISET(SELECT LA0.X FROM (SELECT COLUMN_VALUE X, ROWNUM I FROM TABLE(t.scores) Z) LA0 WHERE LA0.X > 1 ORDER BY LA0.I) AS SYS.ODCINUMBERLIST) END AS big
FROM
 check_complex t